export const getCordeiroDevocionalDoDia = (diaDoMes: number): CalendarioCordeiroDia => {
  const index = (diaDoMes - 1) % CALENDARIO_CORDEIRO_DIAS.length;
  const item = CALENDARIO_CORDEIRO_DIAS[index] || CALENDARIO_CORDEIRO_DIAS[0];
  return {
    ...item,
    dia: diaDoMes
  };
};
